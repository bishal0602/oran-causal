"""Build the manuscript: pdflatex, bibtex, pdflatex twice, output in build/.

Building the supplementary writes generated/esm.tex, the article's numbers of the Online Resource's
sections, tables, figures and results, read from build/supplementary.aux (the supplementary is built
first when both are requested).

Usage (stdlib only, run from anywhere):
    uv run python paper/build.py [sn-article | supplementary ...] [--out DIR]
"""

import argparse
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
DOCS = ("sn-article", "supplementary")
ESM_DOC = "supplementary"
ESM_TEX = Path("generated") / "esm.tex"
PDFLATEX = ("pdflatex", "-synctex=1", "-interaction=nonstopmode", "-file-line-error")
NEWLABEL = r"\newlabel{"
KINDS = {
    "section": "Sect.",
    "subsection": "Sect.",
    "subsubsection": "Sect.",
    "table": "Table",
    "figure": "Fig.",
    "lemma": "Lemma",
    "example": "Example",
    "remark": "Remark",
    "equation": "Eq.",
    "algorithm": "Algorithm",
}
ESM_HEADER = r"""% Generated by paper/build.py from build/supplementary.aux. Do not edit: rebuild the supplementary.
% \esm{label} prints "Online Resource~1, <kind>~<number>", \esmref{label} the number alone.
\makeatletter
\newcommand{\defesm}[3]{\@namedef{esm@k@#1}{#2}\@namedef{esm@n@#1}{#3}}
\newcommand{\esm@get}[2]{\@ifundefined{esm@#1@#2}{\errmessage{Unknown ESM label #2 (not in generated/esm.tex)}}{\@nameuse{esm@#1@#2}}}
\newcommand{\esmref}[1]{\esm@get{n}{#1}}
\newcommand{\esm}[1]{Online Resource~1, \esm@get{k}{#1}~\esm@get{n}{#1}}
\makeatother
"""


def run(cmd: list[str], cwd: Path) -> None:
    """Runs one command and exits with a message when it fails."""
    code = subprocess.run(cmd, cwd=cwd, check=False).returncode
    if code != 0:
        sys.exit(f"{' '.join(cmd)} failed with exit code {code}")


def build(doc: str, root: Path, out: Path) -> Path:
    """Builds one document with the journal recipe and returns its PDF path."""
    out.mkdir(parents=True, exist_ok=True)
    pdflatex = [*PDFLATEX, f"-output-directory={out}", f"{doc}.tex"]
    run(pdflatex, root)
    aux = out / f"{doc}.aux"
    if r"\citation" in aux.read_text(encoding="utf-8", errors="replace"):
        run(["bibtex", str(out / doc)], root)
    run(pdflatex, root)
    run(pdflatex, root)
    return out / f"{doc}.pdf"


def _group(text: str, start: int) -> tuple[str, int]:
    """The balanced brace group opening at `start` and the offset just after it."""
    depth = 0
    for i in range(start, len(text)):
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                return text[start + 1 : i], i + 1
    raise ValueError(f"unbalanced braces at offset {start}")


def _fields(body: str) -> list[str]:
    r"""The top-level brace groups of a `\newlabel` value."""
    fields, i = [], 0
    while i < len(body):
        if body[i] == "{":
            field, i = _group(body, i)
            fields.append(field)
        else:
            i += 1
    return fields


def esm_labels(aux: str) -> dict[str, tuple[str, str]]:
    """Maps each label of a hyperref .aux to its (kind, number), the kind read from its anchor.

    Labels whose anchor is not in `KINDS` are left out.
    """
    labels = {}
    for line in aux.splitlines():
        if not line.startswith(NEWLABEL):
            continue
        key, end = _group(line, len(NEWLABEL) - 1)
        fields = _fields(_group(line, end)[0])
        if len(fields) < 4:
            continue
        kind = KINDS.get(fields[3].split(".", 1)[0])
        if kind is not None:
            labels[key] = (kind, f"({fields[0]})" if kind == "Eq." else fields[0])
    return labels


def esm_tex(labels: dict[str, tuple[str, str]]) -> str:
    r"""The text of generated/esm.tex: the macros and one `\defesm` per label, sorted by label."""
    rows = [rf"\defesm{{{k}}}{{{kind}}}{{{num}}}" for k, (kind, num) in sorted(labels.items())]
    return ESM_HEADER + "\n".join(rows) + "\n"


def write_esm(root: Path, out: Path) -> Path:
    """Writes generated/esm.tex from the supplementary's .aux and returns its path."""
    aux = (out / f"{ESM_DOC}.aux").read_text(encoding="utf-8", errors="replace")
    path = root / ESM_TEX
    path.write_text(esm_tex(esm_labels(aux)), encoding="utf-8", newline="\n")
    return path


def main(argv: list[str] | None = None) -> int:
    """Parses the arguments and builds the requested documents (default: sn-article)."""
    ap = argparse.ArgumentParser(prog="paper/build.py", description=__doc__)
    ap.add_argument("docs", nargs="*", choices=DOCS, metavar="doc")
    ap.add_argument("--root", type=Path, default=ROOT, help="manuscript directory")
    ap.add_argument("--out", type=Path, help="output directory (default: <root>/build)")
    args = ap.parse_args(argv)
    root = args.root.resolve()
    out = (args.out or root / "build").resolve()
    docs = sorted(set(args.docs or DOCS[:1]), key=lambda d: d != ESM_DOC)
    for doc in docs:
        print(build(doc, root, out))
        if doc == ESM_DOC:
            print(write_esm(root, out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
