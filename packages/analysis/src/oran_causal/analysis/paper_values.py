r"""Generates `paper/generated/values.tex`, the numbers the manuscript prints with `\val{key}`.

`spec/values.toml` names every value: a key, the record and JSON pointer it comes from (or an
expression over several), and a format. The generator reads the frozen records, checks them against
`data/manifests`, and writes the `\defval` definitions plus a JSON sidecar that pins each value to
its record sha256 and raw numbers. Regeneration is deterministic: the same records give the same
bytes.

Run `uv run python -m oran_causal.analysis.paper_values` to write both files and
`uv run python -m oran_causal.analysis.paper_values --check` to compare them with the committed
ones.
"""

import argparse
import ast
import csv
import hashlib
import io
import json
import operator
import re
import sys
import tomllib
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path
from typing import Any

from oran_causal.analysis.paper_derived import FUNCTIONS as DERIVED

WORKSPACE_ROOT = Path(__file__).resolve().parents[5]
SPEC_PATH = Path("spec") / "values.toml"
VALUES_TEX = Path("paper") / "generated" / "values.tex"
VALUES_JSON = Path("paper") / "generated" / "values.json"
KEY = re.compile(r"^[a-z][a-z0-9_]*(\.[a-z0-9_]+)+$")
SOURCE = re.compile(r"^(?P<alias>[a-z][a-z0-9_]*):(?P<pointer>/.*)$")
HEADER = (
    "% Generated by oran_causal.analysis.paper_values from spec/values.toml and data/records.\n"
    "% Do not edit: run `uv run python -m oran_causal.analysis.paper_values`.\n"
)

type Number = int | float
type Filter = Callable[[str, Number], str]

_BINARY: dict[type[ast.operator], Callable[[Any, Any], Any]] = {
    ast.Add: operator.add,
    ast.Sub: operator.sub,
    ast.Mult: operator.mul,
    ast.Div: operator.truediv,
}
_FUNCTIONS: dict[str, Callable[..., Any]] = {
    "abs": abs,
    "max": max,
    "min": min,
    "round": round,
    "sum": sum,
    "len": len,
    "dot": lambda a, b: sum(x * y for x, y in zip(a, b, strict=True)),
    **DERIVED,
}


class SpecError(ValueError):
    """The values spec or a record it points to is invalid."""


@dataclass(frozen=True, slots=True)
class Source:
    """A number inside a record: the record path under `data/records` and a JSON pointer."""

    record: str
    pointer: str


@dataclass(frozen=True, slots=True)
class ValueSpec:
    """One printed value: `expr` over named sources, rendered with `fmt`."""

    key: str
    args: Mapping[str, Source]
    expr: str
    fmt: str


@dataclass(frozen=True, slots=True)
class Resolved:
    """A value after reading its records."""

    spec: ValueSpec
    numbers: Mapping[str, Any]
    value: Any
    text: str


FIXED = re.compile(r"^(?P<sign>\+?)\.(?P<digits>\d+)f$")


def _round_half_up(spec: str, value: Number) -> str:
    match = FIXED.match(spec)
    if match is None:
        raise SpecError(f"filter 'up' needs a spec like '.2f' or '+.2f', got {spec!r}")
    quantum = Decimal(1).scaleb(-int(match["digits"]))
    rounded = Decimal(repr(value)).quantize(quantum, rounding=ROUND_HALF_UP)
    return format(rounded, f"{match['sign']}f")


def _apply_filter(name: str, text: str) -> str:
    match name:
        case "math":
            return f"${text}$"
        case "thousands":
            return text.replace(",", r"\,")
        case "sci":
            mantissa, exponent = text.split("e")
            return rf"{mantissa} \times 10^{{{int(exponent)}}}"
        case _:
            raise SpecError(f"unknown format filter {name!r}")


def format_value(value: Number, fmt: str) -> str:
    """Formats a number: a Python format spec, then `|`-separated filters.

    Filters: `up` rounds half up on the decimal repr instead of the binary value (the spec must
    be `.Nf` or `+.Nf`), `x100` scales by 100 first, `thousands` turns `,` into a LaTeX thin space
    (use with a `,` spec), `sci` prints a number given with an `.Ne` spec as `m x 10^{e}` and
    `math` wraps the text in `$...$`.

    Args:
        value: The number to print.
        fmt: For example `.2f`, `+.2f|up|math`, `,d|thousands` or `.1e|sci`.

    Returns:
        The LaTeX text.
    """
    spec, *filters = fmt.split("|")
    if "x100" in filters:
        value = value * 100
    text = _round_half_up(spec, value) if "up" in filters else format(value, spec)
    for name in filters:
        if name not in ("up", "x100"):
            text = _apply_filter(name, text)
    return text


def _evaluate(node: ast.expr, names: Mapping[str, Any]) -> Any:
    match node:
        case ast.Constant(value=value) if isinstance(value, int | float):
            return value
        case ast.Name(id=name) if name in names:
            return names[name]
        case ast.UnaryOp(op=ast.USub(), operand=operand):
            return -_evaluate(operand, names)
        case ast.BinOp(left=left, op=op, right=right) if type(op) in _BINARY:
            return _BINARY[type(op)](_evaluate(left, names), _evaluate(right, names))
        case ast.Call(func=ast.Name(id=func), args=args, keywords=[]) if func in _FUNCTIONS:
            return _FUNCTIONS[func](*(_evaluate(a, names) for a in args))
        case _:
            raise SpecError(f"unsupported expression element {ast.dump(node)}")


def evaluate(expr: str, names: Mapping[str, Any]) -> Any:
    """Evaluates an arithmetic expression over named numbers.

    Allowed: numbers, names, `+ - * /`, unary minus, `abs max min round sum len dot` and the
    functions of `oran_causal.analysis.paper_derived`.
    """
    return _evaluate(ast.parse(expr, mode="eval").body, names)


def _matching(rows: list[Any], part: str) -> list[Any]:
    if part == "*":
        return list(rows)
    wanted = [item.split("=", 1) for item in part.split("&")]
    return [
        row
        for row in rows
        if isinstance(row, dict) and all(str(row.get(k)) == v for k, v in wanted)
    ]


def _step(node: Any, part: str) -> Any:
    if isinstance(node, list):
        if "=" not in part:
            return node[int(part)]
        found = _matching(node, part)
        if len(found) != 1:
            raise SpecError(f"selector {part!r} matches {len(found)} rows, expected one")
        return found[0]
    return node[part]


def _walk(node: Any, parts: Sequence[str], pointer: str) -> Any:
    if not parts:
        return node
    part, rest = parts[0].replace("~1", "/").replace("~0", "~"), parts[1:]
    try:
        if part == "[*]" and isinstance(node, dict):
            return [_walk(member, rest, pointer) for member in node.values()]
        if part.startswith("[") and part.endswith("]") and isinstance(node, list):
            return [_walk(row, rest, pointer) for row in _matching(node, part[1:-1])]
        return _walk(_step(node, part), rest, pointer)
    except (KeyError, IndexError, ValueError, TypeError) as error:
        raise SpecError(f"pointer {pointer} fails at {part!r}") from error


def resolve_pointer(document: Any, pointer: str) -> Any:
    """Follows an RFC 6901 JSON pointer, extended with row selectors.

    A step `field=value&field=value` picks the one element of a list whose fields print as the
    given values. A step `[field=value&field=value]` (or `[*]`) picks every matching element and
    maps the rest of the pointer over them, giving a list; `[*]` on an object maps over its values.

    Raises:
        SpecError: If a step does not exist or a single selector is not unique.
    """
    return _walk(document, pointer.split("/")[1:], pointer)


def _parse_source(text: str, aliases: Mapping[str, str], key: str) -> Source:
    match = SOURCE.match(text)
    if match is None or match["alias"] not in aliases:
        raise SpecError(f"{key}: bad source {text!r}")
    return Source(aliases[match["alias"]], match["pointer"])


def _parse_value(raw: Mapping[str, Any], aliases: Mapping[str, str]) -> ValueSpec:
    key = raw["key"]
    if not KEY.match(key):
        raise SpecError(f"bad key {key!r}")
    if "from" in raw:
        args = {"v": _parse_source(raw["from"], aliases, key)}
        expr = "v"
    else:
        args = {n: _parse_source(s, aliases, key) for n, s in raw["args"].items()}
        expr = raw["expr"]
    return ValueSpec(key, args, expr, raw["fmt"])


def load_spec(path: Path) -> tuple[ValueSpec, ...]:
    """Reads `spec/values.toml`.

    Raises:
        SpecError: On a duplicate key, an unknown alias or a malformed entry.
    """
    document = tomllib.loads(path.read_text(encoding="utf-8"))
    aliases = document["records"]
    specs = tuple(_parse_value(raw, aliases) for raw in document["values"])
    keys = [spec.key for spec in specs]
    duplicates = sorted({key for key in keys if keys.count(key) > 1})
    if duplicates:
        raise SpecError(f"duplicate keys: {', '.join(duplicates)}")
    return specs


def _manifest(root: Path, record_set: str) -> dict[str, str]:
    path = root / "data" / "manifests" / f"{record_set}.sha256"
    entries = (line.split(maxsplit=1) for line in path.read_text(encoding="utf-8").splitlines())
    return {name.removeprefix("*").strip(): digest.lower() for digest, name in entries}


def _cell(text: str) -> Any:
    for kind in (int, float):
        try:
            return kind(text)
        except ValueError:
            continue
    return text


def _parse(record: str, data: bytes) -> Any:
    if record.endswith(".csv"):
        reader = csv.DictReader(io.StringIO(data.decode("utf-8")))
        return [{name: _cell(text) for name, text in row.items()} for row in reader]
    return json.loads(data)


class Records:
    """Reads the JSON records of a workspace once and checks their sha256 against the manifests."""

    def __init__(self, root: Path) -> None:
        """Binds the reader to a workspace root."""
        self.root = root
        self._documents: dict[str, Any] = {}
        self._digests: dict[str, str] = {}

    def digest(self, record: str) -> str:
        """sha256 of the record file, verified against `data/manifests`."""
        self.document(record)
        return self._digests[record]

    def document(self, record: str) -> Any:
        """The parsed JSON of a record."""
        if record not in self._documents:
            data = (self.root / "data" / "records" / record).read_bytes()
            digest = hashlib.sha256(data).hexdigest()
            record_set, _, name = record.partition("/")
            listed = _manifest(self.root, record_set).get(name)
            if listed != digest:
                raise SpecError(f"{record}: sha256 {digest[:12]} differs from manifest {listed}")
            self._digests[record] = digest
            self._documents[record] = _parse(record, data)
        return self._documents[record]


def resolve(spec: ValueSpec, records: Records) -> Resolved:
    """Reads the sources of a value and formats it."""
    numbers = {
        name: resolve_pointer(records.document(source.record), source.pointer)
        for name, source in spec.args.items()
    }
    value = evaluate(spec.expr, numbers)
    return Resolved(spec, numbers, value, format_value(value, spec.fmt))


def render_tex(resolved: Sequence[Resolved]) -> str:
    r"""The `values.tex` text: one `\defval` per key, sorted by key."""
    lines = [rf"\defval{{{r.spec.key}}}{{{r.text}}}" for r in sorted(resolved, key=_by_key)]
    return HEADER + "\n".join(lines) + "\n"


def _by_key(resolved: Resolved) -> str:
    return resolved.spec.key


def _argument(source: Source, value: Any, records: Records) -> dict[str, Any]:
    entry = {
        "record": source.record,
        "sha256": records.digest(source.record),
        "pointer": source.pointer,
    }
    return entry if isinstance(value, dict) else {**entry, "value": value}


def render_json(resolved: Sequence[Resolved], records: Records) -> str:
    """The sidecar: every value with its record hashes, pointers and raw numbers."""
    entries = {
        r.spec.key: {
            "text": r.text,
            "fmt": r.spec.fmt,
            "expr": r.spec.expr,
            "args": {
                name: _argument(source, r.numbers[name], records)
                for name, source in r.spec.args.items()
            },
        }
        for r in sorted(resolved, key=_by_key)
    }
    return json.dumps({"version": 1, "values": entries}, indent=1, sort_keys=True) + "\n"


def generate(root: Path) -> tuple[str, str]:
    """Builds the contents of `values.tex` and `values.json` from the records under `root`."""
    records = Records(root)
    resolved = [resolve(spec, records) for spec in load_spec(root / SPEC_PATH)]
    return render_tex(resolved), render_json(resolved, records)


def _read(path: Path) -> str | None:
    return path.read_bytes().decode("utf-8") if path.is_file() else None


def main(argv: Sequence[str] | None = None) -> int:
    """Writes the generated files, or with `--check` compares them with the committed ones."""
    parser = argparse.ArgumentParser(prog="paper_values", description=__doc__)
    parser.add_argument("--root", type=Path, default=WORKSPACE_ROOT, help="workspace root")
    parser.add_argument("--check", action="store_true", help="exit 1 when the files are stale")
    args = parser.parse_args(argv)
    outputs = dict(zip((VALUES_TEX, VALUES_JSON), generate(args.root), strict=True))
    stale = [name for name, text in outputs.items() if _read(args.root / name) != text]
    if args.check:
        for name in stale:
            print(f"stale: {name}")
        return 1 if stale else 0
    for name, text in outputs.items():
        target = args.root / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
