"""X2 and X3: tables of the dither dose-response and the misspecified-design checks.

X2 varies the dither design (delta, blocks) of the generated data; X3 keeps the data and tells the
method a wrong design (`told` width, switch time or propensity coupling). Both are exploratory
post hoc experiments declared before launch. This module scores their merged campaign records with
the Study 4 cell machinery (`analysis.controlled`) and pools the declared rates per arm.
"""

import argparse
import json
import math
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any

import numpy as np

from oran_causal.analysis.controlled.cells import build_cells, screen
from oran_causal.analysis.controlled.protocol import ANALYSIS_VERSION, RATE_KEYS
from oran_causal.analysis.controlled.tables import clean
from oran_causal.analysis.controlled.validity import mean_ci, rate
from oran_causal.analysis.posthoc.paths import EXTRAS_PROTOCOL, SPECS, lf_sha256, write_text
from oran_causal.analysis.records import load_records
from oran_causal.sim.controlled.datasets.generate import dataset_hash, generate_dataset

EXTRAS_VERSION = "xm-extras/1"
PROTOCOL_REL = "scratchpad/xmethod/EXTRAS_PROTOCOL.md"
TOLD_KEYS = ("width", "shift", "lam")
ABLATION_KEYS = ("centre", "redraw")
FROZEN_DESIGN = (0.10, 20)
WORDING = (
    "These supplementary experiments are exploratory: they were declared before launch "
    f"({PROTOCOL_REL}) on a fresh seed block, use the frozen methods and procedures, and do not "
    "change C1-C3."
)
TREND_KEYS = ("null_decl", "null_raw", "plac_raw")
X2_DELTAS = (0.02, 0.05, 0.10, 0.20)
X3_FAMILIES = {
    "width narrower": (("width", 0.8), ("width", 0.5)),
    "width wider": (("width", 1.25), ("width", 2.0)),
    "switch late": (("shift", 0.02), ("shift", 0.05)),
    "lambda lower": (("lam", 0.8), ("lam", 0.5)),
    "lambda higher": (("lam", 1.25), ("lam", 2.0)),
}
X3_RATE_KEYS = ("null_raw", "plac_raw", "conf_raw", "null_decl", "plac_decl", "conf_decl")

Spec = dict[str, Any]
Row = dict[str, Any]


def load_spec(name_or_path: str | Path, spec_dir: Path | None = None) -> Spec:
    """Reads an extras spec by file path or by name in the frozen specs directory."""
    p = Path(name_or_path)
    if not p.exists():
        p = (spec_dir or SPECS / "extras") / f"{name_or_path}.json"
    return json.loads(p.read_text(encoding="utf-8"))


def check_told(told: Mapping[str, Any]) -> tuple[str, float]:
    """Key and factor of a told variant.

    One of `TOLD_KEYS` maps to a positive factor; X6 adds `centre` and `redraw` (`told` or `true`)
    to a width variant.

    Raises:
        ValueError: If the variant is malformed.
    """
    if not isinstance(told, Mapping):
        raise ValueError(f"told must be a dict: {told!r}")
    main = {k: v for k, v in told.items() if k not in ABLATION_KEYS}
    abl = {k: v for k, v in told.items() if k in ABLATION_KEYS}
    if len(main) != 1 or next(iter(main)) not in TOLD_KEYS:
        raise ValueError(f"told must be one of {TOLD_KEYS} -> factor: {told!r}")
    if abl and (
        next(iter(main)) != "width" or any(v not in ("told", "true") for v in abl.values())
    ):
        raise ValueError(
            f"centre / redraw ('told' | 'true') go with a width variant only: {told!r}"
        )
    k, v = next(iter(main.items()))
    v = float(v)
    if not (math.isfinite(v) and v > 0.0):
        raise ValueError(f"told factor must be > 0: {told!r}")
    return k, v


def design_label(spec: Spec, arm: str) -> str:
    """Human label of the design an arm ran under."""
    ex = spec["extras"]
    if ex["experiment"] == "X2":
        return f"delta {ex['design']['delta']:g} / {ex['design']['n_blocks']} blocks"
    told = spec["arms"][arm].get("told")
    if not told:
        return "exact"
    k, v = check_told(told)
    return {
        "width": f"width x{v:g}",
        "shift": f"switch +{v * 100:g} % of a block",
        "lam": f"lambda x{v:g}",
    }[k]


def design_key(spec: Spec, arm: str) -> list[Any]:
    """Machine key of the design an arm ran under."""
    ex = spec["extras"]
    if ex["experiment"] == "X2":
        return [float(ex["design"]["delta"]), int(ex["design"]["n_blocks"])]
    told = spec["arms"][arm].get("told")
    return list(check_told(told)) if told else ["exact", 1.0]


def repro_check(records: Sequence[Mapping[str, Any]], spec: Spec) -> dict[str, Any]:
    """Data provenance: every distinct dataset of the records regenerated by the frozen generator.

    For X2 delta .10 with 20 blocks and for X3 the records' generated-data hash must equal it;
    for the other X2 designs it must differ (the data changed).
    """
    ex = spec["extras"]
    want_equal = (
        ex["experiment"] == "X3"
        or (
            float(ex["design"]["delta"]),
            int(ex["design"]["n_blocks"]),
        )
        == FROZEN_DESIGN
    )
    seen: dict[tuple, tuple[str | None, str]] = {}
    eq = ne = 0
    for r in records:
        if r.get("status") != "ok":
            continue
        j = r["job"]
        k = (j["world"], j["regime"], j.get("lam"), j["n"], j["seed"], j["kappa"])
        h = r.get("dataset_sha256_generated") or r.get("dataset_sha256")
        if k in seen:
            if seen[k][0] != h:
                return {
                    "ok": False,
                    "why": f"records of dataset {k} disagree on the generated data",
                }
            continue
        ds, _ = generate_dataset(
            j["world"],
            j["regime"],
            j["n"],
            j["seed"],
            lam=1.0 if j.get("lam") is None else j["lam"],
            kappa=j["kappa"],
        )
        seen[k] = (h, dataset_hash(ds))
        eq, ne = eq + (h == seen[k][1]), ne + (h != seen[k][1])
    ok = (ne == 0) if want_equal else (eq == 0)
    return {
        "ok": ok,
        "datasets": len(seen),
        "equal_to_frozen": eq,
        "differ_from_frozen": ne,
        "expected": "equal" if want_equal else "differ",
    }


def rate_view(x: Mapping[str, Any] | None) -> dict[str, Any] | None:
    """The reported fields of a rate."""
    return None if not x else {k: x.get(k) for k in ("rate", "hits", "n", "ci", "validity")}


def pooled_rate(rows: Sequence[Mapping[str, Any]], key: str) -> dict[str, Any] | None:
    """Rate of `key` pooled over seed rows; the clusters are (world, seed), sorted."""
    agg: dict[tuple, list[int]] = {}
    for x in rows:
        c = agg.setdefault((x["world"], x["seed"]), [0, 0])
        c[0] += x["cnt"][key][0]
        c[1] += x["cnt"][key][1]
    ks = sorted(agg)
    return rate([agg[k][0] for k in ks], [agg[k][1] for k in ks])


def _cell_row(spec: Spec, e: Mapping[str, Any]) -> Row:
    prim = e.get("primary") or {}
    return {
        "spec": spec["name"],
        "experiment": spec["extras"]["experiment"],
        "design": design_label(spec, e["arm"]),
        "arm": e["arm"],
        "base_arm": spec["arms"][e["arm"]].get("base", e["arm"]),
        "declare": e["declare"],
        "world": e["world"],
        "regime": e["regime"],
        "lam": e["lam"],
        "n": e["n"],
        "kappa": e["kappa"],
        "status": e["status"],
        "n_measure": e["n_measure"],
        "planned_seeds": e["planned_seeds"],
        "n_infeasible": e["n_infeasible"],
        "n_error": e["n_error"],
        "tau": e["tau"],
        **{k: rate_view(prim.get(k)) for k in RATE_KEYS},
        "recall": prim.get("recall"),
        "validity_label": prim.get("validity"),
    }


def _pooled_row(spec: Spec, arm: str, regime: str, srows: Sequence[Mapping[str, Any]]) -> Row:
    return {
        "spec": spec["name"],
        "experiment": spec["extras"]["experiment"],
        "arm": arm,
        "base_arm": spec["arms"][arm].get("base", arm),
        "declare": spec["arms"][arm]["declare"],
        "regime": regime,
        "design": design_label(spec, arm),
        "design_key": design_key(spec, arm),
        **{k: rate_view(pooled_rate(srows, k)) if srows else None for k in RATE_KEYS},
        "recall": mean_ci([x["recall"] for x in srows]) if srows else None,
    }


def analyse(
    pairs: Sequence[tuple[str | Path, str | Path]],
    protocol_sha256: str | None = None,
    spec_dir: Path | None = None,
) -> dict[str, Any]:
    """Tables of the declared metrics per (spec design, arm, cell).

    Uses `screen` and `build_cells` of the Study 4 analysis: BY declaration for p arms, a
    conformal tau over the cell's tuning records for score-only arms, raw p <= .05 rates and
    recall. Pooled rows add up a (design, arm, regime) over worlds and seeds.

    Args:
        pairs: `(spec, merged records)` pairs; a spec is a path or a name in the extras specs.
        protocol_sha256: LF sha256 of the extras protocol to record; computed from the file when
            None.
        spec_dir: Directory of the extras specs for specs given by name.

    Returns:
        Version stamps, `checks` per spec, `rows`, `pooled`, `x2_trend`, `x3_curve`, `wording`.
    """
    rows, checks, pooled = [], {}, []
    for spec_path, merged in pairs:
        spec = load_spec(spec_path, spec_dir)
        recs = load_records(merged)
        use, scr = screen(recs, spec)
        cells, seed_rows = build_cells(use, spec)
        checks[spec["name"]] = {
            "records": len(recs),
            "used": len(use),
            "duplicates": len(scr["duplicates"]),
            "unexpected": len(scr["unexpected"]),
            "role_mismatch": len(scr["role_mismatch"]),
            "provenance": repro_check(use, spec),
        }
        groups: dict[tuple, list] = {}
        for ck, e in sorted(cells.items()):
            rows.append(_cell_row(spec, e))
            groups.setdefault((e["arm"], e["regime"]), []).extend(seed_rows.get(ck) or [])
        pooled += [
            _pooled_row(spec, arm, regime, srows) for (arm, regime), srows in sorted(groups.items())
        ]
    return {
        "extras_version": EXTRAS_VERSION,
        "analysis": ANALYSIS_VERSION,
        "protocol_sha256": protocol_sha256 or lf_sha256(EXTRAS_PROTOCOL),
        "checks": checks,
        "rows": rows,
        "pooled": pooled,
        "x2_trend": x2_trend(pooled),
        "x3_curve": x3_curve(pooled),
        "wording": WORDING,
    }


def trend_word(values: Sequence[float | None]) -> str:
    """The declared descriptive rule on point estimates in increasing delta; no test."""
    if any(v is None for v in values):
        return "not reported (a design has no rate)"
    d = np.diff([float(v) for v in values if v is not None])
    if np.all(d == 0):
        return "does not change"
    if np.all(d >= 0):
        return "rises"
    if np.all(d <= 0):
        return "falls"
    return "is not monotone"


def x2_trend(pooled: Sequence[Row]) -> list[Row]:
    """Pooled X2 rates per arm and rate over delta, with the trend word.

    Deltas are .02, .05, .10 and .20 at 20 blocks; the 5 and 80 block rates are at delta .10.
    """
    out = []
    x2 = [p for p in pooled if p["experiment"] == "X2"]
    for arm in sorted({p["arm"] for p in x2}):
        by = {tuple(p["design_key"]): p for p in x2 if p["arm"] == arm}
        for k in TREND_KEYS:
            dl = [by.get((d, 20), {}).get(k) for d in X2_DELTAS]
            if all(x is None for x in dl):
                continue
            out.append(
                {
                    "arm": arm,
                    "rate": k,
                    "delta": list(X2_DELTAS),
                    "by_delta": dl,
                    "trend": trend_word([None if x is None else x["rate"] for x in dl]),
                    "blocks_5": by.get((0.10, 5), {}).get(k),
                    "blocks_80": by.get((0.10, 80), {}).get(k),
                }
            )
    return out


def _x3_step_label(k: str, v: float) -> str:
    return f"{k} x{v:g}" if k != "shift" else f"switch +{v * 100:g} %"


def x3_curve(pooled: Sequence[Row]) -> list[Row]:
    """Degradation curve per X3 base arm, regime and family (milder variant first).

    Gives the pooled truth-null and placebo rates and the first variant whose class is INVALID.
    """
    out = []
    x3 = [p for p in pooled if p["experiment"] == "X3"]
    for base, regime in sorted({(p["base_arm"], p["regime"]) for p in x3}):
        by = {
            tuple(p["design_key"]): p for p in x3 if p["base_arm"] == base and p["regime"] == regime
        }
        exact = by.get(("exact", 1.0))
        for fam, steps in X3_FAMILIES.items():
            got = [by.get(s) for s in steps]
            if not any(got):
                continue
            seq = [("exact", exact)] + [
                (_x3_step_label(k, v), g) for (k, v), g in zip(steps, got, strict=True)
            ]
            first = next(
                (
                    lab
                    for lab, g in seq[1:]
                    if g
                    and any((g.get(k) or {}).get("validity") == "INVALID" for k in X3_RATE_KEYS)
                ),
                None,
            )
            out.append(
                {
                    "base_arm": base,
                    "regime": regime,
                    "family": fam,
                    "steps": [
                        {"variant": lab, **{k: (g or {}).get(k) for k in X3_RATE_KEYS}}
                        for lab, g in seq
                    ],
                    "first_invalid": first or "none",
                }
            )
    return out


def rate_text(x: Mapping[str, Any] | None) -> str:
    """`rate (hits/n) [lo, hi]` of a rate view, `NA` when missing."""
    if not x:
        return "NA"
    lo, hi = x["ci"]
    ci = f" [{lo:.3f}, {hi:.3f}]" if lo is not None else ""
    return f"{x['rate']:.3f} ({x['hits']}/{x['n']}){ci}"


def _recall_text(rc: Mapping[str, Any] | None) -> str:
    if not rc:
        return "NA"
    ci = f" [{rc['ci'][0]:.3f}, {rc['ci'][1]:.3f}]" if rc["ci"][0] is not None else ""
    return f"{rc['mean']:.3f}{ci}"


def _md_rows(out: Mapping[str, Any]) -> list[str]:
    lines = [
        "",
        "| spec | design | arm | world | regime | n | status | seeds | tau | truth-null decl | "
        "truth-null raw "
        "| P_placebo decl | P_placebo raw | P_placebo_conf raw | recall [CI] | label |",
        "|" + "---|" * 16,
    ]
    for r in out["rows"]:
        tau = "" if r["tau"] is None else f"{r['tau']:.4g}"
        lam = "" if r["lam"] is None else f" lam {r['lam']:g}"
        lines.append(
            f"| {r['spec']} | {r['design']} | {r['arm']} | {r['world']} | {r['regime']}{lam} | "
            f"{r['n']} | {r['status']} | "
            f"{r['n_measure']}/{r['planned_seeds']} | {tau} | {rate_text(r['null_decl'])} | "
            f"{rate_text(r['null_raw'])} | "
            f"{rate_text(r['plac_decl'])} | {rate_text(r['plac_raw'])} | "
            f"{rate_text(r['conf_raw'])} | {_recall_text(r['recall'])} | "
            f"{r['validity_label'] or ''} |"
        )
    return lines


def _md_pooled(out: Mapping[str, Any]) -> list[str]:
    lines = [
        "",
        "## Pooled per arm (clusters = world x seed)",
        "",
        "| spec | design | arm | regime | truth-null decl | truth-null raw | P_placebo decl | "
        "P_placebo raw | "
        "P_placebo_conf raw | recall [CI] |",
        "|" + "---|" * 10,
    ]
    for p in out["pooled"]:
        lines.append(
            f"| {p['spec']} | {p['design']} | {p['arm']} | {p['regime']} | "
            f"{rate_text(p['null_decl'])} | "
            f"{rate_text(p['null_raw'])} | {rate_text(p['plac_decl'])} | "
            f"{rate_text(p['plac_raw'])} | "
            f"{rate_text(p['conf_raw'])} | {_recall_text(p['recall'])} |"
        )
    return lines


def _md_trends(out: Mapping[str, Any]) -> list[str]:
    lines: list[str] = []
    if out["x2_trend"]:
        lines += [
            "",
            "## X2 dose-response (pooled; trend = declared rule on point estimates, no test)",
            "",
        ]
        for t in out["x2_trend"]:
            by_delta = ", ".join(
                f"delta {d:g} {rate_text(x)}"
                for d, x in zip(t["delta"], t["by_delta"], strict=True)
            )
            lines.append(
                f"- {t['arm']} {t['rate']}: {by_delta}; {t['trend']} with delta; "
                f"5 blocks {rate_text(t['blocks_5'])}, 80 blocks {rate_text(t['blocks_80'])}"
            )
    if out["x3_curve"]:
        lines += [
            "",
            "## X3 degradation curve (first variant with an INVALID pooled rate; descriptive)",
            "",
        ]
        for c in out["x3_curve"]:
            steps = "; ".join(
                f"{s['variant']} null raw {rate_text(s['null_raw'])}, P_placebo raw "
                f"{rate_text(s['plac_raw'])}"
                for s in c["steps"]
            )
            lines.append(
                f"- {c['base_arm']} {c['regime']} {c['family']}: first INVALID at "
                f"{c['first_invalid']}; {steps}"
            )
    return lines


def analyse_md(out: Mapping[str, Any]) -> str:
    """The X2/X3 tables as markdown."""
    lines = [
        "# R-60 extras: tables",
        "",
        f"{out['wording']} Declared in `{PROTOCOL_REL}` (LF sha256 "
        f"{out['protocol_sha256']}). Rates: hits / testable candidates, seed-cluster 95 % "
        "bootstrap CI (eval_analysis). The R-30 class is a descriptive label here, not a verdict.",
        "",
        "## Checks",
        "",
    ]
    for k, c in out["checks"].items():
        lines.append(f"- {k}: {json.dumps(c, sort_keys=True)}")
    lines += _md_rows(out)
    lines += _md_pooled(out)
    lines += _md_trends(out)
    return "\n".join(lines) + "\n"


def write_tables(out: Mapping[str, Any], out_dir: str | Path) -> None:
    """Writes `extras_tables.json` and `EXTRAS_TABLES.md` into `out_dir`."""
    d = Path(out_dir)
    write_text(d / "extras_tables.json", json.dumps(clean(out), indent=1, sort_keys=True))
    write_text(d / "EXTRAS_TABLES.md", analyse_md(out))


def main(argv: Sequence[str] | None = None) -> int:
    """Command line: score extras specs against their merged records."""
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--spec", nargs="+", required=True)
    ap.add_argument("--merged", nargs="+", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    if len(a.spec) != len(a.merged):
        raise SystemExit("--spec and --merged pair up: give as many of each")
    out = analyse(list(zip(a.spec, a.merged, strict=True)))
    write_tables(out, a.out)
    print(json.dumps(out["checks"], indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
