import matplotlib

matplotlib.use("Agg")

import matplotlib.pyplot as plt

from oran_causal.figures import plotted


def _figure(points):
    fig, ax = plt.subplots()
    ax.plot(*zip(*points, strict=True), linestyle="none", marker="o", label="s")
    ax.set_title("t")
    return fig


def test_digest_is_stable():
    a, b = _figure([(0, 1), (1, 2)]), _figure([(0, 1), (1, 2)])
    assert plotted.digest(a) == plotted.digest(b)
    plt.close(a)
    plt.close(b)


def test_marker_order_does_not_matter():
    a, b = _figure([(0, 1), (1, 2), (2, 0)]), _figure([(2, 0), (0, 1), (1, 2)])
    assert plotted.digest(a) == plotted.digest(b)
    plt.close(a)
    plt.close(b)


def test_a_moved_point_changes_the_digest():
    a, b = _figure([(0, 1), (1, 2)]), _figure([(0, 1), (1, 2.01)])
    assert plotted.digest(a) != plotted.digest(b)
    plt.close(a)
    plt.close(b)


def test_text_is_part_of_the_data():
    a = _figure([(0, 1)])
    b = _figure([(0, 1)])
    b.axes[0].set_title("other")
    assert plotted.digest(a) != plotted.digest(b)
    plt.close(a)
    plt.close(b)


def test_rows_list_the_title_and_the_series():
    fig = _figure([(0, 1)])
    kinds = [row[0] for row in plotted.rows(fig)]
    assert "Line2D" in kinds
    assert "Text" in kinds
    plt.close(fig)


def test_table_digest_ignores_the_generator_header():
    one = "% t: generated by x (a.py); do not edit.\n% Sources: p\nbody\n"
    two = "% t: generated by y (b.py); do not edit.\n% Sources: q\nbody\n"
    assert plotted.table_digest(one) == plotted.table_digest(two)
    assert plotted.table_digest(one) != plotted.table_digest(one + "more\n")
