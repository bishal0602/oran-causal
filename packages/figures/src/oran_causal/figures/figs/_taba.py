"""Private helpers of the appendix tables tab_appA_kappa, tab_appB_bridge, tab_appB_cost,
tab_appC_x4, tab_appC_x7, tab_appC_runtime, tab_appC_x2, tab_appC_x3, tab_appC_x5 and tab_appC_x6
(booktabs LaTeX + csv in the journal's ``tables/``). Number formats, the generated-file header,
method labels by family block (paper names via ``oran_causal.figures.methods``) and the writer.
"""

import csv
import math

from oran_causal.figures import methods as M
from oran_causal.figures.paths import tables_dir

MARK = {
    "INVALID": r"$^{\textstyle *}$",
    "INCONCLUSIVE": r"$^{\textstyle\sim}$",
    "VALID": "",
    "NO_READ": r"$^{\textstyle\circ}$",
}  # as tab_study4_env (text-size marks)
DASH = "--"
MINUS = "$-$"


def nan(x) -> bool:
    return x is None or (isinstance(x, float) and math.isnan(x))


def prob(x, nd: int = 3) -> str:
    """A rate in [0, 1] with three decimals (0.052); '--' when missing."""
    if nan(x):
        return DASH
    return f"{x:.{nd}f}"


def short_prob(x: float) -> str:
    """A design probability with at least two decimals and no trailing zero beyond: 0.25, 0.352, 0.50."""
    s = f"{x:.3f}".rstrip("0")
    return s + "0" * max(0, 4 - len(s))


def signed(x, nd: int = 3, plus: bool = True) -> str:
    """A signed number with a math minus (and a plus sign for positive values when ``plus``)."""
    if nan(x):
        return DASH
    s = f"{abs(x):.{nd}f}"
    if round(x, nd) < 0:
        return MINUS + s
    return ("+" if plus and round(x, nd) > 0 else "") + s


def ci(lo, hi, f=prob, **kw) -> str:
    return f"[{f(lo, **kw)}, {f(hi, **kw)}]"


def thousands(n: float) -> str:
    """1328 -> 1\\,328 (thin space, journal style)."""
    s = f"{round(n):,}"
    return s.replace(",", r"\,")


def sig3(x) -> str:
    """CPU seconds to about three significant digits, as the runtime report: 0.055, 0.13, 1.46, 36.7, 185, 1\\,108."""
    if nan(x):
        return DASH
    if x >= 100:
        return thousands(x)
    if x >= 10:
        return f"{x:.1f}"
    if x >= 0.1:
        return f"{x:.2f}"
    return f"{x:.3f}"


def tex_name(code: str) -> str:
    """Paper name of an arm, LaTeX-safe."""
    return M.name(code).replace("≤", r"$\le$")


def short(code: str) -> str:
    """Paper name inside its family block (the block header carries 'design-adjusted' / 'design-blind'), as
    tab_study4_env does: 'Design-adjusted partial correlation' -> 'Partial correlation'.
    """
    n = tex_name(code)
    for pre in ("Design-adjusted ", "Plain "):
        if n.startswith(pre):
            n = n[len(pre) :]
            return n[0].upper() + n[1:]
    return n


def blocks(codes) -> list[tuple[str, list[str]]]:
    """Codes in paper legend order, grouped by family name (design-based, design-adjusted, design-blind)."""
    out: list[tuple[str, list[str]]] = []
    for c in M.order(codes):
        fam = M.family(c).paper
        if out and out[-1][0] == fam:
            out[-1][1].append(c)
        else:
            out.append((fam, [c]))
    return out


def has_name(code: str) -> bool:
    """True if the arm has a paper name (B2 / eq_min / pc_eq / mscr_eq have none and are never shown)."""
    try:
        M.resolve(code)
        return True
    except KeyError:
        return False


def header(name: str, sources: list[str], notes: list[str], module: str | None = None) -> list[str]:
    return (
        [
            f"% {name}: generated by oran-causal-figures (packages/figures/src/oran_causal/figures/figs/{module or name}.py); do not edit.",
            "% Sources: " + ", ".join(sources),
        ]
        + [f"% {n}" for n in notes]
        + ["% Needs \\usepackage{booktabs}."]
    )


def group_row(text: str, ncols: int, italic: bool = True) -> str:
    t = rf"\textit{{{text}}}" if italic else rf"\textbf{{{text}}}"
    return rf"\multicolumn{{{ncols}}}{{@{{}}l}}{{{t}}} \\"


def write(name: str, tex: str, rows: list[dict]) -> list[str]:
    out = tables_dir()
    out.mkdir(parents=True, exist_ok=True)
    tex_path, csv_path = out / f"{name}.tex", out / f"{name}.csv"
    tex_path.write_text(tex, encoding="utf-8")
    fields: list[str] = []
    for r in rows:
        for k in r:
            if k not in fields:
                fields.append(k)
    with open(csv_path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(rows)
    return [str(tex_path), str(csv_path)]
