"""Study 4 verdict grid: claims C1, C2a, C2b, C3 (rows) x environments E1-E5 (columns), as a booktabs LaTeX tabular
plus a csv. Not a figure (no SPEC): run ``uv run python -m oran_causal.figures.figs.tab_study4_verdicts``.

Each cell counts the claim's cells in that environment as the report does (REPORT V1 / V4: INVALID / VALID /
counted; the rest are INCONCLUSIVE), kappa .25, every n. Cell sets per claim (PROTOCOL_A s.10, REPORT s.2-5):
  C1   the design-blind set D (report.json V4_verdicts.C1.D), R2 cells (C1 expects INVALID)
  C2a  PMRT-GBM, R1 + R2 cells
  C2b  the C2b members (design-adjusted partial correlation, Granger), R1 + R2 cells
  C3   PMRT-GBM, E4 R3 cells, every lam (R3 exists in E4 only)
E4 R1 / R2 cells are at lam 1 and are judged on the placebo edge (E4 has no truth-null candidate there). The
environment counts are checked against the verdict table's totals before anything is written.
"""

import csv

from oran_causal.figures.data import load_json
from oran_causal.figures.figs import _study4 as T
from oran_causal.figures.paths import tables_dir

NAME = "tab_study4_verdicts"
SOURCES = [T.SRC_CELLS, T.SRC_REPORT]

# claim -> (row label, report verdict path, cell filter)
CLAIMS = {
    "C1": ("Design-blind tests invalid in R2", ("C1",), lambda v: (v["C1"]["D"], ("R2",))),
    "C2a": ("PMRT-GBM valid in R1 and R2", ("C2a",), lambda v: (["pmrt_nl_eq"], ("R1", "R2"))),
    "C2b": (
        "Design-adjusted tests valid in R1 and R2",
        ("C2b",),
        lambda v: (sorted(v["C2b"]["arms"]), ("R1", "R2")),
    ),
    "C3": (
        "PMRT-GBM valid under the logged confounded policy (R3, E4 only)",
        ("C3",),
        lambda v: (["pmrt_nl_eq"], ("R3",)),
    ),
}


def grid() -> list[dict]:
    rep = load_json(*T.EVAL, "report.json")["tables"]["V4_verdicts"]
    if rep["C1"]["D"] != T.D_ARMS:
        raise AssertionError(f"C1 set D changed: {rep['C1']['D']}")
    c = T.cells()
    rows = []
    for claim, (label, path, sel) in CLAIMS.items():
        arms, regimes = sel(rep)
        s = c[
            c.arm.isin(arms)
            & c.regime.isin(regimes)
            & c.validity.isin(["VALID", "INVALID", "INCONCLUSIVE"])
        ]
        tot = {"INVALID": 0, "VALID": 0, "n": 0}
        for w in [*T.WORLDS, "all"]:
            sw = s if w == "all" else s[s.world == w]
            k = {
                "INVALID": int((sw.validity == "INVALID").sum()),
                "VALID": int((sw.validity == "VALID").sum()),
                "n": len(sw),
            }
            if w != "all":
                for key in tot:
                    tot[key] += k[key]
            rows.append(
                {
                    "claim": claim,
                    "label": label,
                    "methods": "; ".join(T.PAPER[a] for a in arms),
                    "regimes": " + ".join(regimes),
                    "environment": w,
                    "invalid": k["INVALID"],
                    "valid": k["VALID"],
                    "inconclusive": k["n"] - k["INVALID"] - k["VALID"],
                    "counted": k["n"],
                    "verdict": rep[path[0]]["verdict"] if w == "all" else "",
                }
            )
        _check(rep, claim, arms, tot)
    return rows


def _check(rep: dict, claim: str, arms: list, tot: dict) -> None:
    """The environment sums must equal the verdict table's counted / INVALID / VALID cells."""
    if claim == "C1":
        want = {
            "INVALID": sum(rep["C1"]["arms"][a]["r2_invalid"] for a in arms),
            "n": sum(rep["C1"]["arms"][a]["r2_counted"] for a in arms),
        }
    elif claim == "C2b":
        arm = rep["C2b"]["arms"]
        want = {
            "INVALID": sum(arm[a]["n_invalid"] for a in arms),
            "VALID": sum(arm[a]["n_valid"] for a in arms),
            "n": sum(arm[a]["n_cells"] for a in arms),
        }
    else:
        r = rep[claim]
        want = {"INVALID": r["n_invalid"], "VALID": r["n_valid"], "n": r["n_cells"]}
    for k, x in want.items():
        if tot[k] != x:
            raise AssertionError(
                f"{claim} {k}: environments sum to {tot[k]}, verdict table has {x}"
            )


def _cell(r: dict) -> str:
    return "--" if r["counted"] == 0 else f"{r['invalid']}/{r['valid']}/{r['counted']}"


def latex(rows: list[dict]) -> str:
    out = [
        f"% {NAME}: generated by oran-causal-figures (packages/figures/src/oran_causal/figures/figs/{NAME}.py); do not edit.",
        "% Sources: " + ", ".join(SOURCES),
        "% Entries: INVALID / VALID / counted conditions (the rest INCONCLUSIVE), kappa 0.25, every n;"
        " -- = no condition (R3 exists in E4 only).",
        "% Needs \\usepackage{booktabs}.",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{@{}p{4.5cm} c c c c c c@{}}",
        r"\toprule",
        r"\raggedright Claim (methods; regimes): verdict &E1 & E2 & E3 & E4 & E5 & All \\",
        r"\midrule",
    ]
    short = {
        "C1": "design-blind tests; R2",
        "C2a": "PMRT-GBM; R1, R2",
        "C2b": "design-adjusted partial correlation, Granger; R1, R2",
        "C3": "PMRT-GBM; R3, E4 only",
    }
    for claim in CLAIMS:
        rs = {r["environment"]: r for r in rows if r["claim"] == claim}
        cells = " & ".join(_cell(rs[w]) for w in [*T.WORLDS, "all"])
        verdict = rf"\verdict{{{rs['all']['verdict'].lower()}}}"
        out.append(rf"\raggedright {claim} ({short[claim]}): {verdict} & {cells} \\")
    out += [r"\bottomrule", r"\end{tabular}", ""]
    return "\n".join(out)


def write() -> list[str]:
    rows = grid()
    out = tables_dir()
    out.mkdir(parents=True, exist_ok=True)
    tex, csv_path = out / f"{NAME}.tex", out / f"{NAME}.csv"
    tex.write_text(latex(rows), encoding="utf-8")
    with open(csv_path, "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    return [str(tex), str(csv_path)]


if __name__ == "__main__":
    for p in write():
        print("wrote", p)
