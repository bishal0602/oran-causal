"""Appendix A cell table of one Study 4 environment (booktabs LaTeX + csv): every named method x
regime x n, the cell's null-edge rejection rate with its validity mark and the recall of the true
edges. Not a figure (no SPEC): run ``uv run python -m oran_causal.figures.figs.tab_study4_env E1``.

Per cell (kappa .25, 40 seeds; validity_cells.csv and recall_vs_n.csv): the truth-null rate the
cell's validity reads (raw p <= .05 for the p-value methods, declarations for the threshold-only
methods: PC, NOTEARS, SHAP-DAG, two-tower, CDD O-RAN discovery), with the cell's validity mark from
all its reads (truth-null and placebo): * INVALID, ~ INCONCLUSIVE, unmarked VALID, then recall (BY
or threshold declarations; none for an INVALID cell). E4 R1 / R2 have no truth-null candidate: its
rate is the placebo edge. A cell with no validity read at all (NO_READ in validity_cells.csv: the
threshold-only methods in E4 R1 / R2, where the placebo declaration rate is reported but not read
for validity) is marked ° (degree).
"""

import csv
import sys

from oran_causal.figures.data import load_csv
from oran_causal.figures.figs import _study4 as T
from oran_causal.figures.paths import tables_dir

SOURCES = [T.SRC_CELLS, T.SRC_RECALL]
WORLD_NAME = {
    "E1": "Linear graph",
    "E2": "Rare regime",
    "E3": "Delayed harm",
    "E4": "Latent confounding",
    "E5": "Composed",
}  # plain names, as fig_study4_recall
REGIME_NAME = {"R1": "independent logging", "R2": "dithered setpoint"}
GROUPS = [
    ("Design-based tests", ["pmrt_nl_eq", "pmrt_eq"]),
    ("Design-adjusted tests", ["pcorr_eq", "granger_eq", "rcot2_eq"]),
    (
        "Design-blind methods",
        [
            "corr",
            "pcorr_native",
            "pcorr_hac",
            "pcorr_hac_fb",
            "granger_native",
            "rcot2_native",
            "mscr_native",
            "pc_native",
            "notears",
            "shap_dag",
            "two_tower",
            "cdl",
        ],
    ),
]
# LaTeX marks, set at text size (\textstyle) so they print at the table's font size, not as 5-6 pt
# superscripts (V5 s.4)
MARK = {
    "INVALID": r"$^{\textstyle *}$",
    "INCONCLUSIVE": r"$^{\textstyle\sim}$",
    "VALID": "",
    "NO_READ": r"$^{\textstyle\circ}$",
}


def short(arm: str) -> str:
    """Paper name inside its family block (the block header carries "design-adjusted" / design-blind
    "plain").
    """
    n = T.PAPER[arm]
    for pre in ("Design-adjusted ", "Plain "):
        if n.startswith(pre):
            n = n[len(pre) :]
            return n[0].upper() + n[1:]
    return n


def _fmt(x: float, nd: int) -> str:
    return f"{x:.{nd}f}"


def rows_for(world: str) -> list[dict]:
    c = T.cells()
    c = c[c.world == world]
    r = load_csv(*T.EVAL, "csv", "recall_vs_n.csv")
    r = r[r.world == world]
    if world == "E4":
        c, r = c[c.lam == 1.0], r[r.lam == 1.0]
    out = []
    for reg in ("R1", "R2"):
        for _, arms in GROUPS:
            for arm in arms:
                for n in T.NS:
                    cc = c[(c.arm == arm) & (c.regime == reg) & (c.n == n)]
                    if cc.empty:
                        continue
                    if len(cc) != 1:
                        raise AssertionError(f"{world} {reg} {arm} n{n}: {len(cc)} cells")
                    x = cc.iloc[0]
                    raw = x.declare != "tau"
                    col = "null_raw" if raw else "null_decl"
                    if world == "E4":
                        col = "plac_raw" if raw else "plac_decl"
                    rr = r[(r.arm == arm) & (r.regime == reg) & (r.n == n)]
                    rec = (
                        rr.recall_mean.iloc[0]
                        if len(rr) and rr.state.iloc[0] != "INVALID"
                        else float("nan")
                    )
                    out.append(
                        {
                            "world": world,
                            "regime": reg,
                            "arm": arm,
                            "method": T.PAPER[arm],
                            "n": n,
                            "validity": x.validity,
                            "null_kind": col,
                            "null_rate": x[f"{col}_rate"],
                            "null_lo": x[f"{col}_lo"],
                            "null_hi": x[f"{col}_hi"],
                            "recall": rec,
                        }
                    )
    return out


def latex(world: str, rows: list[dict]) -> str:
    name = f"tab_study4_env_{world.lower()}"
    head = [
        f"% {name}: generated by oran-causal-figures (packages/figures/src/oran_causal/figures/figs/tab_study4_env.py); do not edit.",
        "% Sources: " + ", ".join(SOURCES),
        "% Entry: null-edge rejection rate / recall; mark = the condition's validity from all its reads (* INVALID, ~ INCONCLUSIVE,"
        " unmarked VALID, ° no validity read); -- = no recall (INVALID condition);"
        " blank = not in the method's grid. Needs \\usepackage{booktabs}.",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{2.5pt}",
        r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{3.3cm}" + " c" * len(T.NS) + "@{}}",
        r"\toprule",
        "Method & " + " & ".join(f"$n={n}$" for n in T.NS) + r" \\",
    ]
    body = []
    by = {(x["regime"], x["arm"], x["n"]): x for x in rows}
    for reg in ("R1", "R2"):
        body += [
            r"\midrule",
            rf"\multicolumn{{{len(T.NS) + 1}}}{{@{{}}l}}{{\textbf{{{WORLD_NAME[world]}, {REGIME_NAME[reg]}}}}} \\",
        ]
        for group, arms in GROUPS:
            present = [a for a in arms if any((reg, a, n) in by for n in T.NS)]
            if not present:
                continue
            body.append(rf"\multicolumn{{{len(T.NS) + 1}}}{{@{{}}l}}{{\textit{{{group}}}}} \\")
            for arm in present:
                cells = []
                for n in T.NS:
                    x = by.get((reg, arm, n))
                    if x is None:
                        cells.append("")
                        continue
                    rec = "--" if x["recall"] != x["recall"] else _fmt(x["recall"], 2)
                    cells.append(f"{_fmt(x['null_rate'], 3)}{MARK[x['validity']]}/{rec}")
                label = short(arm).replace("≤", r"$\le$")
                body.append(rf"\quad {label} & " + " & ".join(cells) + r" \\")
    return "\n".join(head + body + [r"\bottomrule", r"\end{tabular}", ""])


def write(world: str) -> list[str]:
    rows = rows_for(world)
    out = tables_dir()
    out.mkdir(parents=True, exist_ok=True)
    name = f"tab_study4_env_{world.lower()}"
    tex, csv_path = out / f"{name}.tex", out / f"{name}.csv"
    tex.write_text(latex(world, rows), encoding="utf-8")
    with csv_path.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    return [str(tex), str(csv_path)]


if __name__ == "__main__":
    for world in sys.argv[1:] or ["E1", "E2", "E3", "E4", "E5"]:
        for p in write(world):
            print("wrote", p)
