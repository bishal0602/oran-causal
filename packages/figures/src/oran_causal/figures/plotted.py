"""The data a figure plots, read back from its artists, for regression gates and diffs."""

import hashlib
import io
import json
import re

import matplotlib.colors as mcolors
import numpy as np
from matplotlib.collections import Collection
from matplotlib.figure import Figure
from matplotlib.image import AxesImage
from matplotlib.lines import Line2D
from matplotlib.patches import Patch
from matplotlib.text import Text

DECIMALS = 6


def _num(values) -> list:
    return np.round(np.asarray(values, dtype=float), DECIMALS).tolist()


def _rgba(color) -> list | str:
    try:
        return [round(float(v), DECIMALS) for v in mcolors.to_rgba(color)]
    except ValueError:
        return str(color)


def _text_row(artist: Text) -> list:
    return [
        "Text",
        artist.get_text(),
        _num(artist.get_position()),
        artist.get_fontsize(),
        artist.get_fontweight(),
        _rgba(artist.get_color()),
    ]


def _line_row(artist: Line2D) -> list:
    xy = np.asarray(artist.get_xydata(), dtype=float).reshape(-1, 2)
    if artist.get_linestyle() == "None":
        xy = xy[np.lexsort((xy[:, 1], xy[:, 0]))]
    return [
        "Line2D",
        artist.get_label(),
        _num(xy[:, 0]),
        _num(xy[:, 1]),
        _rgba(artist.get_color()),
        artist.get_linestyle(),
        artist.get_marker(),
        artist.get_linewidth(),
    ]


def _image_row(artist: AxesImage) -> list:
    return ["AxesImage", _num(np.ma.filled(artist.get_array().astype(float), np.nan))]


def _collection_row(artist: Collection) -> list:
    array = artist.get_array()
    vertices = b"".join(np.round(p.vertices, DECIMALS).tobytes() for p in artist.get_paths())
    return [
        type(artist).__name__,
        _num(np.ma.filled(artist.get_offsets(), np.nan)),
        None if array is None else _num(np.ma.filled(array.astype(float), np.nan)),
        [_rgba(c) for c in artist.get_facecolor()][:50],
        hashlib.md5(vertices, usedforsecurity=False).hexdigest(),
    ]


def _patch_row(artist: Patch) -> list:
    path = artist.get_path().transformed(artist.get_patch_transform())
    return [
        type(artist).__name__,
        _num(path.vertices),
        _rgba(artist.get_facecolor()),
        _rgba(artist.get_edgecolor()),
        artist.get_linewidth(),
    ]


def rows(fig: Figure) -> list[list]:
    """Rows of every artist of the figure that carries data, in draw order.

    Args:
    fig: A built figure.

    Returns: One row per text, line, image, collection and patch; marker-only lines list their
    points sorted.
    """
    out = []
    for artist in fig.findobj():
        if isinstance(artist, Text):
            if artist.get_text().strip():
                out.append(_text_row(artist))
        elif isinstance(artist, Line2D):
            out.append(_line_row(artist))
        elif isinstance(artist, AxesImage):
            out.append(_image_row(artist))
        elif isinstance(artist, Collection):
            out.append(_collection_row(artist))
        elif isinstance(artist, Patch):
            out.append(_patch_row(artist))
    return out


def digest(fig: Figure) -> str:
    """MD5 of the rows of the figure."""
    payload = json.dumps(rows(fig), default=str).encode()
    return hashlib.md5(payload, usedforsecurity=False).hexdigest()


def pdf_layout(fig: Figure) -> dict:
    """Page boxes, page count and font names of the PDF the figure saves to."""
    buf = io.BytesIO()
    fig.savefig(buf, format="pdf")
    data = buf.getvalue()
    boxes = [m.decode() for m in re.findall(rb"/MediaBox\s*\[([^\]]*)\]", data)]
    names = {m.decode() for m in re.findall(rb"/BaseFont\s*/([A-Za-z0-9+\-_,]+)", data)}
    fonts = sorted(re.sub(r"^[A-Z]{6}\+", "", n) for n in names)
    return {"mediabox": boxes, "fonts": fonts, "pages": len(re.findall(rb"/Type\s*/Page\b", data))}


def table_digest(text: str) -> str:
    """SHA-256 of a generated table without its generator header and source lines."""
    kept = [
        line
        for line in text.splitlines()
        if not (
            line.startswith("% ")
            and (": generated by" in line or line.startswith(("% Sources:", "% Per-edge rows")))
        )
    ]
    return hashlib.sha256("\n".join(kept).encode()).hexdigest()
